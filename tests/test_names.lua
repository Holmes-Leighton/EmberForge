print("== cleaning names")
local ok, s = Nick.Clean("  Rocky   Jr  ")
expect(ok and s == "Rocky Jr", "extra spaces are trimmed and squeezed (" .. tostring(s) .. ")")
ok, s = Nick.Clean("<b>Hax</b> & \"co\"")
expect(ok and s == "bHax/bco" or ok and not s:find("[<>&\"]"), "rich-text markup characters are removed (" .. tostring(s) .. ")")
ok, s = Nick.Clean("line\nbreak\ttab")
expect(ok and s == "line break tab", "control characters become spaces (" .. tostring(s) .. ")")
ok, s = Nick.Clean("")
expect(ok and s == "", "blank is allowed (it removes the name)")
ok, s = Nick.Clean(string.rep("a", Nick.MAX_LENGTH))
expect(ok, "exactly the limit is fine")
ok, s = Nick.Clean(string.rep("a", Nick.MAX_LENGTH + 1))
expect(not ok and s:find(tostring(Nick.MAX_LENGTH)), "one over the limit is refused with a clear reason (" .. tostring(s) .. ")")
ok = Nick.Clean(nil)
expect(not ok, "a non-string is refused")
ok = Nick.Clean("\xff\xfe")
expect(not ok, "broken UTF-8 is refused")
expect(Nick.Trim(string.rep("b", 30)) == string.rep("b", Nick.MAX_LENGTH), "typing is cut at the limit")
expect(utf8.len(Nick.Trim(string.rep("é", 30))) == Nick.MAX_LENGTH, "cutting never splits a multi-byte character")

print("== naming a Golem")
local p, q = newPlayer(1, "Alice"), newPlayer(2, "Bob")
local d, dq = PDS.Load(p), PDS.Load(q)
local golem = { id = "g1", element = "Frost", tier = 3, deployed = false }
table.insert(d.Golems, golem)
table.insert(dq.Golems, { id = "g9", element = "Ember", tier = 1, deployed = false })
local before = GN.Describe(golem)
expect(before.nickname == nil and before.shortName == "Frost Golem", "an unnamed Golem keeps its usual name")
local res, out = Names.Rename(p, "golem", "g1", "Rocky")
expect(res and out == "Rocky" and golem.nickname == "Rocky", "naming works and is saved on the Golem")
local after = GN.Describe(golem)
expect(after.shortName == "Rocky" and after.name == "Rocky the " .. before.name, "lists say 'Rocky the Frost Core Golem', over its head just 'Rocky' (" .. after.name .. ")")
res, out = Names.Rename(p, "golem", "g1", "Again")
expect(not res and golem.nickname == "Rocky", "a second try straight away is held back by the cooldown (" .. tostring(out) .. ")")
Names.OnPlayerLeave(p)
res, out = Names.Rename(p, "golem", "g9", "Mine now")
expect(not res and dq.Golems[1].nickname == nil, "you can't name someone else's Golem (" .. tostring(out) .. ")")
Names.OnPlayerLeave(p)
res, out = Names.Rename(p, "golem", "nope", "X")
expect(not res, "an unknown Golem id is refused")
Names.OnPlayerLeave(p)
res = Names.Rename(p, "golem", "g1", string.rep("z", 40))
expect(not res and golem.nickname == "Rocky", "a name that is too long is refused and the old one stays")
Names.OnPlayerLeave(p)
res = Names.Rename(p, "sword", "g1", "Hax")
expect(not res, "an unknown kind is refused")
Names.OnPlayerLeave(p)
golem.deployed = true
res = Names.Rename(p, "golem", "g1", "Boulder")
expect(res and golem.nickname == "Boulder", "a Golem at work can be renamed too")
Names.OnPlayerLeave(p)
res, out = Names.Rename(p, "golem", "g1", "   ")
expect(res and out == nil and golem.nickname == nil, "a blank name removes the nickname")
expect(GN.Describe(golem).shortName == "Frost Golem", "and the usual name comes back")

print("== Roblox text filter")
local ts = game:GetService("TextService")
ts.FilterStringAsync = function(_, text)
    return { GetNonChatStringForBroadcastAsync = function() return (text:lower():find("bad") and string.rep("#", #text)) or text end }
end
Names.OnPlayerLeave(p)
res, out = Names.Rename(p, "golem", "g1", "Badger")
expect(not res and golem.nickname == nil and tostring(out):find("isn't allowed"), "a name the filter changes is refused, not saved with #### in it (" .. tostring(out) .. ")")
Names.OnPlayerLeave(p)
res = Names.Rename(p, "golem", "g1", "Goodie")
expect(res and golem.nickname == "Goodie", "a name the filter passes is saved")
ts.FilterStringAsync = function() error("filter down") end
Names.OnPlayerLeave(p)
res, out = Names.Rename(p, "golem", "g1", "Offline")
expect(not res and golem.nickname == "Goodie", "if the filter fails the name is refused (" .. tostring(out) .. ")")
ts.FilterStringAsync = nil

